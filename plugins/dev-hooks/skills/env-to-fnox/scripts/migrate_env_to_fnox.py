#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.12"
# dependencies = []
# ///
"""Automate the common-case .env -> fnox migration SKILL.md walks through by hand.

For the Bitwarden Secrets Manager provider (this skill's default): parses a `.env`
file and writes a reference-only `fnox.toml` (step 4's shape): one `bitwarden-sm`
provider, a `{ provider, value = key-name }` row per secret, `{ default = "..." }` rows
for the `--config` variables (plain config, no vault) and references to existing keys
for `--shared`. It then stores each secret with `fnox -c <output> set VAR -p bws -k
<key>`, the value on stdin, never on a command line.

The BWS token is read once with `fnox get -c ~/.config/fnox/config.toml
BWS_ACCESS_TOKEN` (the keychain-backed global secret) and put only in each `fnox set`
child's env: never printed, never exported to this process or any other child.
`fnox set` does not bootstrap that token itself, unlike `fnox exec`.

`--verify` resolves every variable from the new config and compares it with the
`.env`, printing only `same`, `different` or `unresolved` per variable. A `different`
usually means the key name already existed in the project. `--delete-source` removes
the `.env` after a typed "DELETE" prompt.

Usage:
  migrate_env_to_fnox.py --env-file .env --project-id <PROJECT_ID> [--output fnox.toml]
                          [--key-prefix my-repo-] [--config VAR ...]
                          [--shared VAR=key-name ...]
                          [--dry-run] [--verify] [--delete-source]

Exit code: 0 = success (including a --dry-run preview), 1 = a dotenv/fnox/
verification/confirmation error, 2 = a command-line usage error (argparse).
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

PROVIDER_NAME = "bws"
TOKEN_VAR = "BWS_ACCESS_TOKEN"
TOKEN_TIMEOUT_S = 60  # a locked keychain can hang the read forever

# Mirrors the upstream Ruby dotenv rules exactly: a bare unquoted value, a single-quoted
# literal, or a double-quoted value with only \\ and \" escapes -- anything else aborts
# rather than guessing at shell-like expansion this isn't actually doing.
_KEY_RE = re.compile(r"\A([A-Za-z_][A-Za-z0-9_]*)=(.*)\Z")
_BARE_RE = re.compile(r"""\A[^\s#'"`$\\]+\Z""")
_SINGLE_RE = re.compile(r"\A'[^']*'\Z")
_DOUBLE_RE = re.compile(r'\A"(?:[^"\\$`]|\\[\\"])*"\Z')
_DOUBLE_ESCAPE_RE = re.compile(r'\\([\\"])')
_PROJECT_ID_RE = re.compile(r"\A[A-Za-z0-9-]+\Z")


class DotenvError(Exception):
    """A single-line, user-facing message about unsupported/malformed dotenv syntax."""


def parse_dotenv_value(raw: str, line_no: int) -> str:
    """Decode one RHS per the rules above; raises DotenvError on anything else."""
    if raw == "" or _BARE_RE.fullmatch(raw):
        return raw
    if _SINGLE_RE.fullmatch(raw):
        return raw[1:-1]
    if _DOUBLE_RE.fullmatch(raw):
        return _DOUBLE_ESCAPE_RE.sub(r"\1", raw[1:-1])
    raise DotenvError(f"Unsupported dotenv value syntax on line {line_no}")


def parse_dotenv(path: Path) -> dict[str, str]:
    """Parse a .env file into {KEY: value}. Blank lines and full-line `#` comments are
    skipped; a key repeated later in the file overwrites the earlier value (last wins,
    matching the upstream Ruby port). Pure and subprocess-free -- exercised directly by
    running the whole CLI under --dry-run."""
    values: dict[str, str] = {}
    for i, line in enumerate(Path(path).read_text().splitlines(), start=1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        m = _KEY_RE.fullmatch(line)
        if not m:
            raise DotenvError(f"Unsupported dotenv syntax on line {i}")
        values[m.group(1)] = parse_dotenv_value(m.group(2), i)
    return values


def bws_key_name(env_key: str, prefix: str = "") -> str:
    """DATABASE_URL -> <prefix>database-url, the key-name convention SKILL.md uses."""
    return prefix + env_key.lower().replace("_", "-")


def _toml_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_fnox_toml(
    project_id: str,
    references: dict[str, str],
    config: dict[str, str],
) -> str:
    """Build the fnox.toml text SKILL.md's step 4 documents by hand. `references`
    maps ENV_VAR -> Secrets Manager KEY NAME, never the secret itself; only `config`
    maps to a value, the plain non-secret defaults. Pure string-building, no I/O."""
    lines = [
        "# Generated by migrate_env_to_fnox.py -- references only, no secret values.",
        "# Run commands as `fnox exec -- <cmd>`.",
        "[providers]",
        f'{PROVIDER_NAME} = {{ type = "bitwarden-sm", project_id = {_toml_string(project_id)} }}',
        "",
        "[secrets]",
    ]
    for key, key_name in references.items():
        lines.append(
            f"{key} = {{ provider = {_toml_string(PROVIDER_NAME)}, "
            f"value = {_toml_string(key_name)} }}"
        )
    for key, value in config.items():
        lines.append(f"{key} = {{ default = {_toml_string(value)} }}")
    lines.append("")
    return "\n".join(lines)


# --- thin, mockable subprocess wrappers -------------------------------------------
# Kept to a single subprocess.run call each so tests can put a stub `fnox` first on
# PATH rather than needing a real Bitwarden account.


def run_fnox_get(env_key, config_path, fnox_bin, timeout=None):
    """`fnox get -c <config> <KEY>`; the caller keeps stdout in-process."""
    return subprocess.run(
        [fnox_bin, "get", "-c", str(config_path), env_key],
        capture_output=True,
        text=True,
        check=False,
        timeout=timeout,
    )


def run_fnox_set(env_key, key_name, value, config_path, token, fnox_bin):
    """`fnox -c <config> set VAR -p bws -k <key>` with the value on stdin and the BWS
    token in this one child's env."""
    return subprocess.run(
        [fnox_bin, "-c", str(config_path), "set", env_key]
        + ["-p", PROVIDER_NAME, "-k", key_name],
        input=value,
        capture_output=True,
        text=True,
        check=False,
        env={**os.environ, TOKEN_VAR: token},
    )


def read_bws_token(fnox_bin) -> str | None:
    """The keychain-backed token from the global fnox config, or None."""
    config = Path.home() / ".config" / "fnox" / "config.toml"
    try:
        result = run_fnox_get(TOKEN_VAR, config, fnox_bin, timeout=TOKEN_TIMEOUT_S)
    except subprocess.TimeoutExpired:
        return None
    token = result.stdout.strip()
    return token if result.returncode == 0 and token else None


def die(message: str, code: int = 1) -> int:
    print(f"migrate_env_to_fnox: {message}", file=sys.stderr)
    return code


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description="Migrate a .env file to fnox + Bitwarden Secrets Manager, "
        "automating the steps env-to-fnox/SKILL.md documents by hand."
    )
    p.add_argument("--env-file", required=True, help="path to the .env file to migrate")
    p.add_argument(
        "--project-id",
        required=True,
        help="Bitwarden Secrets Manager project ID (the vault scope for `bws`)",
    )
    p.add_argument(
        "--output",
        default="fnox.toml",
        help="path to write the generated fnox.toml (default: fnox.toml)",
    )
    p.add_argument(
        "--key-prefix",
        default="",
        help="prefix for every new key name, e.g. `my-repo-` gives my-repo-database-url",
    )
    p.add_argument(
        "--config",
        nargs="+",
        action="extend",
        default=[],
        metavar="VAR",
        help="non-secret variables to write as `{ default = ... }`, with no vault",
    )
    p.add_argument(
        "--shared",
        nargs="+",
        action="extend",
        default=[],
        metavar="VAR=key-name",
        help="reference an existing key in the project instead of creating one",
    )
    p.add_argument(
        "--dry-run",
        action="store_true",
        help="print what would be migrated; makes no fnox calls and writes nothing",
    )
    p.add_argument(
        "--verify",
        action="store_true",
        help="after writing, compare each resolved value with the .env "
        "(prints only same/different/unresolved)",
    )
    p.add_argument(
        "--delete-source",
        action="store_true",
        help="remove --env-file once migrated (asks for a typed DELETE confirmation)",
    )
    return p


def verify(values, output_path, fnox_bin) -> list[str]:
    """Print same/different/unresolved per variable; return the ones not `same`."""
    bad = []
    for key, expected in values.items():
        result = run_fnox_get(key, output_path, fnox_bin)
        if result.returncode != 0:
            verdict = "unresolved"
        elif result.stdout.removesuffix("\n") == expected:
            verdict = "same"
        else:
            verdict = "different"
        print(f"{key}: {verdict}")
        if verdict != "same":
            bad.append(key)
    return bad


def main(argv: list[str]) -> int:
    args = build_parser().parse_args(argv)

    if not _PROJECT_ID_RE.fullmatch(args.project_id):
        return die("--project-id may contain only letters, numbers, and hyphens")

    env_path = Path(args.env_file)
    if not env_path.exists():
        return die(f"no such file: {args.env_file}")

    try:
        values = parse_dotenv(env_path)
    except DotenvError as e:
        return die(str(e))

    if not values:
        return die("no dotenv assignments found")

    for key in args.config:
        if key not in values:
            return die(f"--config {key} is not in {env_path}")
    shared = {}
    for item in args.shared:
        key, sep, key_name = item.partition("=")
        if not (sep and key and key_name):
            return die(f"--shared takes VAR=key-name, got {item!r}")
        if key in args.config:
            return die(f"{key} is both --config and --shared")
        shared[key] = key_name
    config = {key: values[key] for key in args.config}
    secrets = {
        key: bws_key_name(key, args.key_prefix)
        for key in values
        if key not in config and key not in shared
    }

    if args.dry_run:
        print(f"Would migrate {len(values)} variable(s): {', '.join(sorted(values))}")
        for key, key_name in secrets.items():
            print(f"  secret  {key} -> {key_name}")
        for key, key_name in shared.items():
            print(f"  shared  {key} -> {key_name}")
        for key in config:
            print(f"  config  {key} (plain default in fnox.toml)")
        return 0

    fnox_bin = shutil.which("fnox")
    if not fnox_bin:
        return die(
            "fnox CLI not found on PATH (run `mise use -g fnox "
            "bitwarden-secrets-manager` per SKILL.md step 2)"
        )

    token = read_bws_token(fnox_bin) if secrets else ""
    if token is None:
        return die(
            f"could not read {TOKEN_VAR} from ~/.config/fnox/config.toml "
            "(is the keychain unlocked, and is the token stored there? "
            "See SKILL.md step 2)"
        )

    output_path = Path(args.output)
    output_path.write_text(
        render_fnox_toml(args.project_id, {**secrets, **shared}, config)
    )
    output_path.chmod(0o600)
    print(f"Wrote {output_path}")

    for key, key_name in secrets.items():
        result = run_fnox_set(key, key_name, values[key], output_path, token, fnox_bin)
        if result.returncode != 0:
            return die(
                f"fnox set failed for {key} ({key_name}): "
                f"{result.stderr.strip() or result.stdout.strip()} "
                f"-- {output_path} was written; secrets before {key} were stored"
            )
        print(f"Stored secret: {key_name}  ({key})")

    if args.verify:
        bad = verify(values, output_path, fnox_bin)
        if bad:
            return die(
                f"verification failed for: {', '.join(bad)} -- `different` usually "
                "means the key name already existed in the project (pick another "
                "--key-prefix); `unresolved` means fnox could not read it "
                "(see SKILL.md step 7)"
            )
        print(f"Verified {len(values)} variable(s) match {env_path}.")

    if args.delete_source:
        answer = input(f'Type DELETE to remove "{env_path}": ')
        if answer != "DELETE":
            return die(
                f"confirmation did not match -- {env_path} was NOT deleted "
                "(the secrets and fnox.toml above were already written)"
            )
        env_path.unlink()
        print(f"Removed {env_path}")

    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
